(** Tests for Story #482 — Gemini CLI parity uplift (Gemini CLI 0.38.2).

    Covers:
    - AC1: JSON headless and stream-json support reflected in capabilities
    - AC2: MCP wired as settings-file based (Gemini reads settings.json;
           no per-invocation file injection); no secrets in generated config
    - AC3: Workspace [.gemini/settings.json] config strategy implemented;
           GEMINI.md is project context and not generated by default
    - AC4: Parity targets stable channel only, not preview or nightly *)

open Cabal

let contains_str s needle =
  let len = String.length s and nlen = String.length needle in
  let rec loop i =
    i + nlen <= len && (String.sub s i nlen = needle || loop (i + 1))
  in
  nlen = 0 || loop 0

let with_tmpdir f =
  let dir = Filename.temp_dir "epure_test_482_" "" in
  Fun.protect
    ~finally:(fun () ->
      ignore (Sys.command (Printf.sprintf "rm -rf %s" (Filename.quote dir))))
    (fun () -> f dir)

let rec ensure_parent_dir path =
  let dir = Filename.dirname path in
  if dir = path || dir = "." then ()
  else begin
    ensure_parent_dir dir ;
    if not (Sys.file_exists dir) then Unix.mkdir dir 0o755
  end

let write_file path content =
  ensure_parent_dir path ;
  let oc = open_out path in
  output_string oc content ;
  close_out oc

let read_file path =
  let ic = open_in_bin path in
  let n = in_channel_length ic in
  let buf = Bytes.create n in
  really_input ic buf 0 n ;
  close_in ic ;
  Bytes.to_string buf

let epure_mcp_server () =
  Backend_types.make_mcp_server_config
    ~name:"epure"
    ~command:"epure-mcp-server"
    ~args:["--stdio"]
    ~env:[("EPURE_PROJECT", "/tmp/project")]
    ()

let task_spec_with_mcp dir =
  Backend_types.make_task_spec
    ~prompt:"test"
    ~working_dir:dir
    ~mcp_servers:[epure_mcp_server ()]
    ()

let check_failed_with_mcp_path result path =
  match result.Backend_types.status with
  | Backend_types.Failed msg ->
      Alcotest.(check bool) "failure mentions MCP" true (contains_str msg "MCP") ;
      Alcotest.(check bool)
        "failure mentions settings path"
        true
        (contains_str msg path)
  | _ -> Alcotest.fail "expected Gemini run_task to fail before invocation"

