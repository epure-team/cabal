(** {1 AC3 — settings generation is idempotent} *)

let test_gemini_config_idempotent () =
  match
    ( Backend_config_gen.generate ~backend_id:"gemini-cli",
      Backend_config_gen.generate ~backend_id:"gemini-cli" )
  with
  | None, _ | _, None -> Alcotest.fail "expected artifact for gemini-cli"
  | Some a1, Some a2 ->
      Alcotest.(check string)
        "AC3: two generate calls produce identical content"
        a1.Backend_config_gen.content
        a2.Backend_config_gen.content

