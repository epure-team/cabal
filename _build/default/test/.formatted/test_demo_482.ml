let test_gemini_config_points_mcp_to_workspace_settings () =
  match Backend_config_gen.generate ~backend_id:"gemini-cli" with
  | None -> Alcotest.fail "expected artifact for gemini-cli"
  | Some a -> (
      Alcotest.(check string)
        "AC2: generated path is workspace settings"
        ".gemini/settings.json"
        a.Backend_config_gen.project_relative_path ;
      let json = Yojson.Safe.from_string a.Backend_config_gen.content in
      match json with
      | `Assoc fields when List.mem_assoc "mcpServers" fields -> ()
      | _ -> Alcotest.fail "expected top-level mcpServers")

(** {1 AC2 — Generated settings MCP map is empty by default} *)

let test_gemini_config_mcp_is_disabled () =
  match Backend_config_gen.generate ~backend_id:"gemini-cli" with
  | None -> Alcotest.fail "expected artifact for gemini-cli"
  | Some a -> (
      let json = Yojson.Safe.from_string a.Backend_config_gen.content in
      match json with
      | `Assoc fields -> (
          match List.assoc_opt "mcpServers" fields with
          | Some (`Assoc []) -> ()
          | Some other ->
              Alcotest.failf
                "expected empty mcpServers, got %s"
                (Yojson.Safe.to_string other)
          | None -> Alcotest.fail "expected mcpServers")
      | _ -> Alcotest.fail "expected settings JSON object")

(** {1 AC2 — Generated config contains no secrets} *)

let test_gemini_config_no_secrets () =
  match Backend_config_gen.generate ~backend_id:"gemini-cli" with
  | None -> Alcotest.fail "expected artifact for gemini-cli"
  | Some a ->
      let content = String.lowercase_ascii a.Backend_config_gen.content in
      let secret_keywords =
        ["password"; "credential"; "bearer"; "private_key"]
      in
      List.iter
        (fun kw ->
          Alcotest.(check bool)
            ("AC2: no secret keyword '" ^ kw ^ "' in config")
            false
            (contains_str content kw))
        secret_keywords

let test_gemini_run_fails_when_user_settings_blocks_requested_mcp () =
  with_tmpdir (fun dir ->
      let settings_path = Filename.concat dir ".gemini/settings.json" in
      let original = {|{"mcpServers":{"user":{"command":"user-mcp"}}}|} in
      write_file settings_path original ;
      Eio_posix.run @@ fun env ->
      Eio.Switch.run @@ fun sw ->
      let result = Gemini_cli.run_task ~sw ~env (task_spec_with_mcp dir) in
      check_failed_with_mcp_path result ".gemini/settings.json" ;
      Alcotest.(check string)
        "user-authored settings unchanged"
        original
        (read_file settings_path))

let test_gemini_run_fails_when_hash_mismatch_blocks_requested_mcp () =
  with_tmpdir (fun dir ->
      ignore
        (Backend_config_gen.setup_project_config
           ~mcp_servers:[]
           ~backend_id:"gemini-cli"
           ~project_dir:dir
           ~force:false) ;
      let settings_path = Filename.concat dir ".gemini/settings.json" in
      let modified = {|{"mcpServers":{"user":{"command":"modified"}}}|} in
      write_file settings_path modified ;
      Eio_posix.run @@ fun env ->
      Eio.Switch.run @@ fun sw ->
      let result = Gemini_cli.run_task ~sw ~env (task_spec_with_mcp dir) in
      check_failed_with_mcp_path result ".gemini/settings.json" ;
      Alcotest.(check string)
        "hash-mismatched settings unchanged"
        modified
        (read_file settings_path))

